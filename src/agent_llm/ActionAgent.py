class ActionAgent:
    '''
    刀具磨損是不可逆的物理結構損耗（時間只會增加不會減少）。
    Agent 無法透過調參數把磨損的刀變新。因此，一旦進入 200~240 分鐘高危區，
    改修動作是立刻調低加工進給速度（降低扭矩壓力），並發出最高優先級換刀工單，
    強行撐過最後幾分鐘。
    '''
    SCHEDULE_TOOL_CHANGE = "排程換刀" #TWF

    '''
    HDF 的死亡線是「溫差 < 8.6K 且 轉速 < 1380 rpm」。
    Agent 的改修動作是強制將主軸轉速往上拉高 200~300 rpm。
    轉速拉高後，不僅直接脫離 < 1380 的危險區，
    馬達高速運轉帶動的風扇排風也會強行將製程溫度拉開，擴大溫差，瞬間破壞 HDF 的觸發條件！
    '''
    COOLING_COMPENSATION = "熱補償改修" #HDF

    '''
    功率過高（>9000W）通常是負載太重或馬達卡死；功率過低（<3500W）是空轉。
    Agent 的改修動作是動態反向調節扭矩（Torque）。
    若快衝破 9000W，直接強制砍斷扭矩；若快跌破 3500W，則微幅拉高扭矩，硬把功率拉回安全範圍。
    '''
    POWER_STABILIZATION = "功率穩定改修" #PWF

    '''
    OSF 是 磨損 × 扭矩 超標。既然磨損扣不掉，
    Agent 的改修動作就是對扭矩進行「切頂（Clip）」強制閹割！直接把扭矩砍掉 15%~30%，
    讓相乘積絕對無法衝破 11,000 的結構死亡線。
    '''
    STRESS_RELIEF = "應力釋放改修" #OSF


    '''
    RNF 是外部突發干擾，物理參數無法預防。
    但當 DT Agent 發現不穩定度訊號連續抖動時，
    Knowledge Agent 的動作是立刻對當前數值進行寫入備份，
    並啟動電磁防護或隔離機制，防止隨機干擾擴大。
    '''
    FAIL_SAFE_SNAPSHOT = "安全快照隔離" #RNF

